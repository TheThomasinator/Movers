SELECT STAFF.staffID FROM STAFF  
WHERE STAFF.staffID = 1
AND  
(SELECT  
(SELECT COUNT(STAFF_MAINTENANCE.maintenanceID) FROM STAFF_MAINTENANCE  
INNER JOIN STAFF  
ON  STAFF_MAINTENANCE.staffID = STAFF.staffID  
INNER JOIN MAINTENANCE  
ON STAFF_MAINTENANCE.maintenanceID = MAINTENANCE.maintenanceID  
WHERE NOT MAINTENANCE.dateOfMaintenance BETWEEN '2025-12-04 13:00' and '2025-12-04 14:00'  
AND NOT DATEADD(MINUTE, MAINTENANCE.duration, MAINTENANCE.dateOfMaintenance) BETWEEN '2025-12-04 13:00' and '2025-12-04 14:00'  
AND NOT '2025-12-04 13:00' BETWEEN MAINTENANCE.dateOfMaintenance and DATEADD(MINUTE, MAINTENANCE.duration, MAINTENANCE.dateOfMaintenance)  
AND NOT '2025-12-04 14:00' BETWEEN MAINTENANCE.dateOfMaintenance and DATEADD(MINUTE, MAINTENANCE.duration, MAINTENANCE.dateOfMaintenance)  
AND STAFF_MAINTENANCE.staffID = 1)  
+  
(SELECT  
(SELECT COUNT(STAFF_TRAINING.trainingId) FROM STAFF_TRAINING  
INNER JOIN STAFF  
ON  STAFF_TRAINING.staffID = STAFF.staffID  
INNER JOIN TRAINING  
ON STAFF_TRAINING.trainingId = TRAINING.trainingId  
AND NOT TRAINING.dateOfTraining BETWEEN '2025-12-04 13:00' and '2025-12-04 14:00'  
AND NOT DATEADD(MINUTE, TRAINING.duration, TRAINING.dateOfTraining) BETWEEN '2025-12-04 13:00' and '2025-12-04 14:00'  
AND NOT '2025-12-04 13:00' BETWEEN TRAINING.dateOfTraining and DATEADD(MINUTE, TRAINING.duration, TRAINING.dateOfTraining)  
AND NOT '2025-12-04 14:00' BETWEEN TRAINING.dateOfTraining and DATEADD(MINUTE, TRAINING.duration, TRAINING.dateOfTraining)  
AND STAFF_TRAINING.staffID = 1)))  
=  
(SELECT  
(SELECT COUNT(STAFF_MAINTENANCE.maintenanceID) FROM STAFF_MAINTENANCE WHERE STAFF_MAINTENANCE.staffID = 1  
AND STAFF_MAINTENANCE.staffID = 1) +  
(SELECT COUNT(STAFF_TRAINING.trainingID) FROM STAFF_TRAINING WHERE STAFF_TRAINING.staffID = 1))  
AND (((STAFF.staffId IN (SELECT staffId FROM STAFF_TRAINING INNER JOIN TRAINING ON STAFF_TRAINING.trainingID = TRAINING.trainingID WHERE TRAINING.trainingType = 'Training1'))  
AND(STAFF.staffId IN(SELECT staffId FROM STAFF_TRAINING INNER JOIN TRAINING ON STAFF_TRAINING.trainingID = TRAINING.trainingID WHERE TRAINING.trainingType = 'Training2')) 
AND(STAFF.staffId IN(SELECT staffId FROM STAFF_TRAINING INNER JOIN TRAINING ON STAFF_TRAINING.trainingID = TRAINING.trainingID WHERE TRAINING.trainingType = 'Training3')) 
AND STAFF.jobTitle = 'Driver') 
OR STAFF.jobTitle = 'Maintenance Engineer' 
)
