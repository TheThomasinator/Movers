CREATE TABLE [ADDRESS]
(
	addressID INT IDENTITY(1,1) NOT NULL,
	firstLine VARCHAR(20) NOT NULL,
	secondLine VARCHAR(20) NOT NULL,
	postCode VARCHAR(8) NOT NULL,
	county VARCHAR(20) NOT NULL,
	city VARCHAR(20) NOT NULL
	PRIMARY KEY(addressID)
)

CREATE TABLE JOB
(
	jobID INT IDENTITY(1,1) NOT NULL,
	addressID INT NOT NULL,
	jobType VARCHAR(20) NOT NULL,
	dateOfJob DATETIME NOT NULL
	PRIMARY KEY(jobID)
	FOREIGN KEY(addressID) REFERENCES [ADDRESS]
)

CREATE TABLE STAFF
(
	staffID INT IDENTITY(1,1) NOT NULL, 
	firstName VARCHAR(20) NOT NULL,
	lastName VARCHAR(20) NOT NULL,
	jobTitle VARCHAR(15) NOT NULL,
	partOrFullTime VARCHAR(4) NOT NULL
	PRIMARY KEY(staffID)
)

CREATE TABLE VAN
(
	vanID INT IDENTITY(1,1) NOT NULL,
	size VARCHAR(10) NOT NULL
	PRIMARY KEY(vanID)
)

CREATE TABLE MAINTENANCE
(
	maintenanceID INT IDENTITY(1,1) NOT NULL,
	maintenanceType VARCHAR(10) NOT NULL,
	dateOfMaintenance DATETIME NOT NULL
	PRIMARY KEY(maintenanceID)
)

CREATE TABLE TRAINING
(
	trainingID INT IDENTITY(1,1) NOT NULL,
	trainingType VARCHAR(20) NOT NULL,
	dateOfTraining DATETIME NOT NULL
	PRIMARY KEY(trainingID)
)

CREATE TABLE STOCK
(
	stockID INT IDENTITY(1,1) NOT NULL,
	stockName VARCHAR(20) NOT NULL,
	price MONEY NOT NULL,
	quantInStock INT NOT NULL
	PRIMARY KEY(stockID)
)

CREATE TABLE [ORDER]
(
	orderID INT IDENTITY(1,1) NOT NULL,
	dateOrdered DATETIME NOT NULL,
	orderArrived BIT NOT NULL
	PRIMARY KEY(orderID)
)

CREATE TABLE STAFF_JOB
(
	staffID	INT NOT NULL FOREIGN KEY REFERENCES STAFF(staffID),
	jobID INT NOT NULL FOREIGN KEY REFERENCES JOB(jobID)
	PRIMARY KEY(staffID, jobID),	
)

CREATE TABLE VAN_JOB
(
	vanID	INT NOT NULL FOREIGN KEY REFERENCES VAN,
	jobID INT NOT NULL FOREIGN KEY REFERENCES JOB
	PRIMARY KEY(vanID, jobID)
)

CREATE TABLE STAFF_MAINTENANCE
(
	staffID	INT NOT NULL FOREIGN KEY REFERENCES STAFF,
	maintenanceID INT NOT NULL FOREIGN KEY REFERENCES MAINTENANCE
	PRIMARY KEY(staffID, maintenanceID)	
)


CREATE TABLE STOCK_ORDER
(
	stockID INT NOT NULL FOREIGN KEY REFERENCES STOCK(stockID),
	orderID INT NOT NULL FOREIGN KEY REFERENCES [ORDER](orderID),
	quantityOrdered INT NOT NULL
	PRIMARY KEY(stockID, orderID)	
)

CREATE TABLE STAFF_JOB
(
	staffID	INT NOT NULL FOREIGN KEY REFERENCES STAFF(staffID),
	jobID INT NOT NULL FOREIGN KEY REFERENCES JOB(jobID)
	PRIMARY KEY(staffID, jobID),	
)

CREATE TABLE STAFF_TRAINING
(
	staffID	INT NOT NULL FOREIGN KEY REFERENCES STAFF,
	trainingID INT NOT NULL FOREIGN KEY REFERENCES TRAINING
	PRIMARY KEY(staffID, trainingID)
)

CREATE TABLE STAFF_MAINTENANCE
(
	staffID	INT NOT NULL FOREIGN KEY REFERENCES STAFF,
	maintenanceID INT NOT NULL FOREIGN KEY REFERENCES MAINTENANCE
	PRIMARY KEY(staffID, maintenanceID)	
)