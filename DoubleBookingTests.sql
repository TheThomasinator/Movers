SELECT MAINTENANCE.vanId FROM MAINTENANCE
WHERE
(SELECT COUNT (MAINTENANCE.vanId) FROM MAINTENANCE 
WHERE vanId = 2
AND NOT MAINTENANCE.dateOfMaintenance BETWEEN '11-11-2025 10:00:00' and '11-11-2025 11:00:00' 
AND NOT DATEADD(MINUTE, MAINTENANCE.duration, MAINTENANCE.dateOfMaintenance) BETWEEN '11-11-2025 10:00:00' and '11-11-2025 11:00:00' 
AND NOT '11-11-2025 10:00:00' BETWEEN MAINTENANCE.dateOfMaintenance and DATEADD(MINUTE,  MAINTENANCE.duration,  MAINTENANCE.dateOfMaintenance) 
AND NOT '11-11-2025 11:00:00' BETWEEN MAINTENANCE.dateOfMaintenance and DATEADD(MINUTE,  MAINTENANCE.duration,  MAINTENANCE.dateOfMaintenance))
=
(SELECT COUNT(MAINTENANCE.vanId) FROM MAINTENANCE WHERE MAINTENANCE.vanId = 2)
AND vanId = 2

SELECT VAN.vanId FROM VAN WHERE vanId NOT IN(SELECT vanId FROM MAINTENANCE)